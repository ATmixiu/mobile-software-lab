function getCategoryNews(name) {
  return categoryData[name] || []
}


function getParentByCategory(name) {
  return parentMap[name] || ''
}


function getHomeSections() {

  let names = [
    '海大要闻',
    '综合新闻',
    '学术海大',
    '校园纵横',
    '院系聚焦'
  ]

  let result = []

  for (let i = 0; i < names.length; i++) {

    let name = names[i]

    result.push({
      name: name,
      parent: getParentByCategory(name),
      newsList: getCategoryNews(name).slice(0, 3)
    })

  }

  return result
}


function getAllNews() {

  let result = []

  for (let name in categoryData) {

    let list = categoryData[name]

    for (let i = 0; i < list.length; i++) {

      let item = Object.assign({}, list[i])

      item.category = name
      item.parent = getParentByCategory(name)

      result.push(item)
    }

  }

  return result
}


function getNewsDetail(id) {

  for (let name in categoryData) {

    let list = categoryData[name]

    for (let i = 0; i < list.length; i++) {

      if (list[i].id == id) {

        let news = Object.assign({}, list[i])

        news.category = name
        news.parent = getParentByCategory(name)

        return {
          code: '200',
          news: news
        }

      }

    }

  }

  return {
    code: '404',
    news: {}
  }
}


